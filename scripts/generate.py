#!/usr/bin/env python3
"""Generate Go resources and endpoint services from a pinned public contract."""
import argparse
import hashlib
import json
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = '// Code generated by scripts/generate.py; DO NOT EDIT.\n\n'
VERBS = {'get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'}
INITIALISMS = {'id': 'ID', 'url': 'URL', 'api': 'API', 'ip': 'IP', 'utc': 'UTC', 'utf8': 'UTF8', 'cpf': 'CPF', 'cnpj': 'CNPJ'}


def name(value):
    value = unicodedata.normalize('NFKD', value).encode('ascii', 'ignore').decode()
    parts = re.findall('[A-Za-z0-9]+', value)
    result = ''.join(INITIALISMS.get(p.lower(), p[:1].upper() + p[1:]) for p in parts)
    if not result or result[0].isdigit():
        result = 'Value' + result
    return result


def comment(value):
    return ' '.join(str(value).split()).replace('*/', '* /')


def query_schema(parameter):
    result = dict(parameter['schema'])
    if parameter.get('description'):
        result['description'] = parameter['description']
    if 'example' in parameter:
        result['example'] = parameter['example']
    elif parameter.get('examples'):
        values = [example['value'] for example in parameter['examples'].values() if 'value' in example]
        if values:
            result.pop('example', None)
            result['examples'] = values
    return result


def query_documentation(schema):
    parts = [comment(schema.get('description', 'is defined by the public API.'))]
    labels = [('default', 'Padrão'), ('minimum', 'Mínimo'), ('maximum', 'Máximo'),
              ('minLength', 'Comprimento mínimo'), ('maxLength', 'Comprimento máximo'),
              ('minItems', 'Quantidade mínima'), ('maxItems', 'Quantidade máxima')]
    for key, label in labels:
        if key in schema:
            parts.append(label + ': ' + json.dumps(schema[key], ensure_ascii=False) + '.')
    examples = [schema['example']] if 'example' in schema else schema.get('examples', [])
    if examples:
        parts.append('Exemplo: ' + json.dumps(examples[0], ensure_ascii=False) + '.')
    return ' '.join(parts)


class Generator:
    def __init__(self):
        self.source = json.loads((ROOT / 'contracts/source.json').read_text(encoding='utf-8-sig'))
        raw = (ROOT / 'contracts/openapi.json').read_bytes()
        if hashlib.sha256(raw).hexdigest() != self.source['sha256']:
            raise ValueError('Pinned contract hash differs from contracts/source.json')
        self.spec = json.loads(raw)
        self.schemas = dict(self.spec['components']['schemas'])
        self.services = json.loads((ROOT / 'contracts/service-map.json').read_text(encoding='utf-8-sig'))
        self.operations = {}
        self.outputs = {}
        self.input_types = set()
        self.query_types = set()
        self.enums = {}
        for path, item in self.spec['paths'].items():
            for method, op in item.items():
                if method not in VERBS:
                    continue
                key = op['operationId']
                if key in self.operations or op.get('x-raims-availability', 'production') != 'production':
                    raise ValueError('Duplicate or unpublished operation: ' + key)
                self.operations[key] = dict(op, path=path, method=method.upper(), parameters=item.get('parameters', []) + op.get('parameters', []))
        mapped = [op for methods in self.services.values() for op in methods.values()]
        if len(mapped) != len(set(mapped)) or set(mapped) != set(self.operations) or len(mapped) != self.source['operations']:
            raise ValueError('Service map must cover the pinned operations exactly once')
        for key, op in self.operations.items():
            self.validate_security(op.get('security', self.spec.get('security', [])), key)
            body = op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
            if op.get('requestBody') and not body:
                raise ValueError('Only JSON request bodies are implemented: ' + key)
            if body:
                bodyname = self.schema_reference(body, key + ' request')
                self.input_types.add(bodyname)
            for parameter in op['parameters']:
                parameter = self.resolve(parameter)
                if parameter['in'] not in {'path', 'query', 'header'} or (parameter['in'] == 'header' and parameter['name'] not in {'Idempotency-Key', 'X-Raims-Environment'}):
                    raise ValueError('Unsupported parameter: ' + key + ' ' + parameter['name'])
                self.validate(parameter['schema'])
        self.validate(self.schemas)

    def validate_security(self, requirements, operation):
        expected = {('BearerAuth', ()), ('ApplicationOAuth', ('raims:api',))}
        actual = set()
        if not isinstance(requirements, list) or len(requirements) != len(expected):
            raise ValueError('Authentication alternatives need explicit runtime support: ' + operation)
        for requirement in requirements:
            if not isinstance(requirement, dict) or len(requirement) != 1:
                raise ValueError('Combined authentication needs explicit runtime support: ' + operation)
            scheme, scopes = next(iter(requirement.items()))
            if not isinstance(scopes, list) or any(not isinstance(scope, str) for scope in scopes) or len(scopes) != len(set(scopes)):
                raise ValueError('Authentication scopes need explicit runtime support: ' + operation)
            actual.add((scheme, tuple(sorted(scopes))))
        if actual != expected:
            raise ValueError('Authentication changes need explicit runtime support: ' + operation)
        definitions = self.spec['components'].get('securitySchemes', {})
        bearer = definitions.get('BearerAuth', {})
        oauth = definitions.get('ApplicationOAuth', {})
        if bearer.get('type') != 'http' or bearer.get('scheme', '').lower() != 'bearer' or oauth.get('type') != 'oauth2':
            raise ValueError('Authentication scheme definitions need explicit runtime support: ' + operation)

    def schema_reference(self, schema, location):
        reference = schema.get('$ref', '')
        supported = {'$ref', 'title', 'description', 'example', 'examples', 'deprecated'}
        if not isinstance(reference, str) or not reference.startswith('#/components/schemas/') or set(schema) - supported:
            raise ValueError('Only component schema references are implemented for ' + location)
        schema_name = reference[len('#/components/schemas/'):]
        if schema_name not in self.schemas:
            raise ValueError('Unknown component schema for ' + location)
        return schema_name

    def resolve(self, schema):
        if '$ref' not in schema:
            return schema
        ref = schema['$ref']
        if not ref.startswith('#/components/'):
            raise ValueError('External refs are unsupported: ' + ref)
        value = self.spec
        for part in ref[2:].split('/'):
            value = value[part.replace('~1', '/').replace('~0', '~')]
        return dict(value, **{k: v for k, v in schema.items() if k != '$ref'})

    def validate(self, value):
        if isinstance(value, dict):
            kind = value.get('type')
            if isinstance(kind, list):
                if any(not isinstance(item, str) for item in kind) or len(kind) != len(set(kind)) or len([item for item in kind if item != 'null']) != 1:
                    raise ValueError('Only one concrete schema type combined with null is implemented')
            if '$ref' in value:
                self.schema_reference(value, 'schema properties')
                self.resolve(value)
            if 'oneOf' in value or 'allOf' in value:
                raise ValueError('Unsupported schema composition')
            if 'anyOf' in value:
                branches = value['anyOf']
                if len(branches) != 2 or sum(x.get('type') == 'null' for x in branches) != 1:
                    raise ValueError('Only nullable anyOf is supported')
            for v in value.values():
                self.validate(v)
        elif isinstance(value, list):
            for v in value:
                self.validate(v)

    def normalize(self, schema):
        schema = dict(schema)
        if 'anyOf' in schema:
            child = next(x for x in schema.pop('anyOf') if x.get('type') != 'null')
            schema = dict(child, **schema)
            schema['nullable'] = True
        return schema

    def typename(self, schema_name):
        return schema_name[:-7] + 'Params' if schema_name in self.input_types and schema_name.endswith('Request') else schema_name

    def gotype(self, schema, owner, field, is_input):
        schema = self.normalize(schema)
        if '$ref' in schema:
            return self.typename(schema['$ref'].split('/')[-1])
        kind = schema.get('type')
        if isinstance(kind, list):
            concrete = [item for item in kind if item != 'null']
            if len(concrete) != 1:
                raise ValueError('Only one concrete schema type combined with null is implemented')
            kind = concrete[0]
        if kind == 'string':
            return 'string'
        if kind == 'integer':
            return 'int64'
        if kind == 'number':
            return 'json.Number'
        if kind == 'boolean':
            return 'bool'
        if kind == 'array':
            item = self.gotype(schema['items'], owner, field + 'Item', is_input)
            if self.nullable(schema['items']):
                item = '*' + item
            return '[]' + item
        if kind == 'object':
            if schema.get('properties'):
                nested = owner + name(field)
                if nested not in self.schemas:
                    self.schemas[nested] = schema
                    if is_input:
                        self.input_types.add(nested)
                return self.typename(nested)
            additional = schema.get('additionalProperties', True)
            if isinstance(additional, dict):
                typ = self.gotype(additional, owner, field + 'Value', is_input)
                if self.nullable(additional):
                    typ = '*' + typ
                return 'map[string]' + typ
            return 'map[string]json.RawMessage'
        raise ValueError('Unsupported schema type: ' + str(schema))

    def nullable(self, schema):
        schema = self.resolve(self.normalize(schema))
        return schema.get('nullable', False) or 'null' in (schema.get('type') if isinstance(schema.get('type'), list) else [])

    def render_type(self, schema_name, schema):
        is_input = schema_name in self.input_types
        typ = self.typename(schema_name)
        result = '// ' + typ + ' ' + comment(schema.get('description', 'contains the fields defined by the public API.')) + '\n'
        result += 'type ' + typ + ' struct {\n'
        if not is_input:
            result += '\tResource `json:"-"`\n'
        used = set()
        for field, value in schema.get('properties', {}).items():
            fieldname = name(field)
            if fieldname in used or fieldname in {'Resource', 'RawJSON', 'LastResponse', 'ExtraFields'}:
                raise ValueError('Go field collision in ' + schema_name)
            used.add(fieldname)
            fieldtype = self.gotype(value, typ, field, is_input)
            if is_input:
                fieldtype = 'Optional[' + fieldtype + ']'
                tag = field + ',omitzero'
            else:
                if self.nullable(value) or field not in schema.get('required', []):
                    fieldtype = '*' + fieldtype
                tag = field
            documentation = query_documentation(value) if schema_name in self.query_types else comment(value.get('description', 'is defined by the public API.'))
            result += '\t// ' + fieldname + ' ' + documentation + '\n'
            result += '\t' + fieldname + ' ' + fieldtype + ' `json:"' + tag + '"`\n'
            self.add_enum(typ + fieldname, self.resolve(self.normalize(value)))
            if value.get('items'):
                self.add_enum(typ + fieldname + 'Item', value['items'])
        result += '}\n\n'
        if not is_input:
            result += '// UnmarshalJSON validates and reads the public ' + typ + ' response.\n'
            result += 'func (v *' + typ + ') UnmarshalJSON(data []byte) error {\n'
            result += '\ttype plain ' + typ + '\n\tvar decoded plain\n'
            result += '\tresource, err := decodeResource(data, ' + json.dumps(schema_name) + ', &decoded)\n\tif err != nil { return err }\n'
            result += '\t*v = ' + typ + '(decoded)\n\tv.Resource = resource\n\treturn nil\n}\n\n'
            result += '// MarshalJSON encodes typed fields and future fields, preserving received field presence.\n'
            result += 'func (v ' + typ + ') MarshalJSON() ([]byte, error) {\n'
            result += '\ttype plain ' + typ + '\n\treturn encodeResource(v.Resource, plain(v), ' + json.dumps(schema_name) + ')\n}\n\n'
        return result

    def add_enum(self, prefix, schema):
        values = schema.get('enum', [])
        labels = schema.get('x-raims-enum-labels', values)
        for value, label in zip(values, labels):
            if value is None or not isinstance(label, str):
                continue
            symbol = prefix + name(label)
            self.enums[symbol] = value

    def generate(self):
        catalog = {}
        service_source = MARKER + 'package raims\n\nimport "context"\n\n'
        client_init = []
        docs = ['# Go SDK reference\n\n', 'Generated from the pinned public contract. `Params` uses `Set(value)` to send a field and `Null[T]()` to send null. All methods accept `context.Context`, the IDs shown in the path and optional request options. Inspect type fields with `go doc`.\n\n', '| Service and method | Endpoint | Parameters | Return type | Status | OAuth environments | Idempotency |\n| --- | --- | --- | --- | --- | --- | --- |\n']
        for service, methods in self.services.items():
            public_service = {'SimulationCharges': 'Simulations.Charges', 'SimulationRefunds': 'Simulations.Refunds'}.get(service, service)
            service_source += '// ' + service + 'Service provides the endpoints available through Client.' + public_service + '.\n'
            service_source += 'type ' + service + 'Service struct { client *Client }\n\n'
            if not service.startswith('Simulation'):
                client_init.append('client.' + service + ' = &' + service + 'Service{client: client}')
            for method, key in methods.items():
                op = self.operations[key]
                parameters = [self.resolve(p) for p in op['parameters']]
                path_params = [p for p in parameters if p['in'] == 'path']
                queries = [p for p in parameters if p['in'] == 'query']
                body = op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
                if queries and body:
                    raise ValueError('Combined query and body needs explicit support')
                params_name = None
                params_schema = None
                if body:
                    params_schema = body['$ref'].split('/')[-1]
                    params_name = self.typename(params_schema)
                elif queries:
                    params_schema = key + 'Params'
                    self.input_types.add(params_schema)
                    self.query_types.add(params_schema)
                    self.schemas[params_schema] = {'type': 'object', 'additionalProperties': False, 'properties': {p['name']: query_schema(p) for p in queries}, 'required': [p['name'] for p in queries if p.get('required')]}
                    params_name = params_schema
                successes = {}
                for status, response in op['responses'].items():
                    if status.isdigit() and 200 <= int(status) < 300:
                        response = self.resolve(response)
                        schema = response.get('content', {}).get('application/json', {}).get('schema', {})
                        if response.get('content') and not schema:
                            raise ValueError('Only JSON response bodies are implemented: ' + key)
                        successes[status] = self.schema_reference(schema, key + ' response ' + status) if schema else ''
                result_types = set(x for x in successes.values() if x)
                if result_types and any(not value for value in successes.values()):
                    raise ValueError('Mixed empty and JSON success responses need explicit runtime support: ' + key)
                output = next(iter(result_types)) if result_types else None
                if len(result_types) > 1:
                    output = key + 'Result'
                    merged, required = {}, None
                    for result in sorted(result_types):
                        child = self.schemas[result]
                        merged.update(child['properties'])
                        keys = set(child.get('required', []))
                        required = keys if required is None else required.intersection(keys)
                    self.schemas[output] = {'type': 'object', 'properties': merged, 'required': sorted(required), 'additionalProperties': False}
                env = next((p['schema']['enum'] for p in parameters if p.get('name') == 'X-Raims-Environment'), [])
                if not env:
                    raise ValueError('OAuth environments missing for ' + key)
                idem = any(p.get('name') == 'Idempotency-Key' for p in parameters)
                catalog[key] = {'method': op['method'], 'path': op['path'], 'params': params_schema or '', 'body': bool(body), 'body_required': op.get('requestBody', {}).get('required', False), 'responses': successes, 'environments': env, 'idempotency': idem, 'path_parameters': {p['name']: p['schema'] for p in path_params}, 'max_body_bytes': op.get('x-raims-max-body-bytes', 0)}
                signature = 'ctx context.Context'
                for p in path_params:
                    signature += ', ' + p['name'] + ' string'
                if params_name:
                    signature += ', params *' + params_name
                signature += ', options ...RequestOption'
                return_type = '*' + output if output else '*Response'
                service_source += '// ' + method + ' ' + comment(op.get('summary', key)) + '\n'
                service_source += 'func (s *' + service + 'Service) ' + method + '(' + signature + ') (' + return_type + ', error) {\n'
                paths = 'map[string]string{' + ', '.join(json.dumps(p['name']) + ': ' + p['name'] for p in path_params) + '}' if path_params else 'nil'
                args = 'params' if params_name else 'nil'
                if output:
                    service_source += '\treturn request[' + output + '](ctx, s.client, ' + json.dumps(key) + ', ' + paths + ', ' + args + ', options...)\n}\n\n'
                else:
                    service_source += '\treturn s.client.execute(ctx, ' + json.dumps(key) + ', ' + paths + ', nil, nil, options...)\n}\n\n'
                if output and queries and 'page' in self.schemas[output].get('properties', {}):
                    item = self.schemas[output]['properties']['list']['items']['$ref'].split('/')[-1]
                    service_source += '// ' + method + 'All lazily follows forward cursors and preserves the original filters.\n'
                    service_source += 'func (s *' + service + 'Service) ' + method + 'All(' + signature + ') *Iterator[' + item + '] {\n'
                    service_source += '\treturn newIterator[' + item + '](ctx, s.client, ' + json.dumps(key) + ', ' + paths + ', params, options...)\n}\n\n'
                    if output not in getattr(self, 'pages', set()):
                        service_source += 'func (v *' + output + ') pagination() pageInfo { return pageInfo{HasNext: v.Page.HasNext, HasPrevious: v.Page.HasPrevious, NextAfter: v.Page.NextAfter, PreviousBefore: v.Page.PreviousBefore} }\n\n'
                        service_source += '// NextPage loads the next page with the original filters and request options.\n// It returns nil when there is no continuation. The context controls the new request.\n'
                        service_source += 'func (v *' + output + ') NextPage(ctx context.Context) (*' + output + ', error) { return fetchPage[' + output + '](ctx, &v.Resource, v.pagination(), false) }\n\n'
                        service_source += '// PreviousPage loads the previous page with the original filters and request options.\n// It returns nil when there is no previous page. The context controls the new request.\n'
                        service_source += 'func (v *' + output + ') PreviousPage(ctx context.Context) (*' + output + ', error) { return fetchPage[' + output + '](ctx, &v.Resource, v.pagination(), true) }\n\n'
                    if not hasattr(self, 'pages'):
                        self.pages = set()
                    self.pages.add(output)
                public_service = {'SimulationCharges': 'Simulations.Charges', 'SimulationRefunds': 'Simulations.Refunds'}.get(service, service)
                docs.append('| `' + public_service + '.' + method + '` | `' + op['method'] + ' ' + op['path'] + '` | `' + (params_name or 'none') + '` | `' + (output or 'Response') + '` | ' + ', '.join(sorted(successes)) + ' | ' + ', '.join(env) + ' | ' + ('Yes' if idem else 'No') + ' |\n')
        self.outputs['services_generated.go'] = service_source
        self.outputs['client_generated.go'] = MARKER + 'package raims\n\n// SimulationsService groups the endpoints that require Sandbox credentials.\ntype SimulationsService struct {\n// Charges provides charge payment and scenario simulations.\nCharges *SimulationChargesService\n// Refunds provides refund completion and failure simulations.\nRefunds *SimulationRefundsService\n}\n\nfunc initServices(client *Client) {\n' + '\n'.join(client_init) + '\nclient.Simulations = &SimulationsService{Charges: &SimulationChargesService{client: client}, Refunds: &SimulationRefundsService{client: client}}\n}\n'
        models = MARKER + 'package raims\n\nimport "encoding/json"\n\n'
        done = set()
        while set(self.schemas) - done:
            for typ in sorted(set(self.schemas) - done):
                models += self.render_type(typ, self.schemas[typ])
                done.add(typ)
        self.outputs['models_generated.go'] = models
        constants = MARKER + 'package raims\n\n// These constants preserve the environment and enum wire values published by the API.\nconst (\n'
        environments = sorted(set(v for op in catalog.values() for v in op['environments']))
        for environment in environments:
            constants += name(environment) + ' Environment = ' + json.dumps(environment) + '\n'
        for symbol, value in sorted(self.enums.items()):
            value_type = ' int64' if isinstance(value, int) and not isinstance(value, bool) else ''
            constants += symbol + value_type + ' = ' + json.dumps(value, ensure_ascii=False) + '\n'
        self.outputs['enums_generated.go'] = constants + ')\n'
        self.outputs['contracts/operations.json'] = json.dumps(catalog, ensure_ascii=False, indent=2) + '\n'
        self.outputs['contracts/schemas.json'] = json.dumps(self.schemas, ensure_ascii=False, separators=(',', ':')) + '\n'
        self.outputs['docs/reference.md'] = ''.join(docs)
        for path, content in list(self.outputs.items()):
            if path.endswith('.go'):
                self.outputs[path] = subprocess.run(['gofmt'], input=content.encode(), stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True).stdout.decode()

    def write(self, check):
        bad = []
        for path, content in self.outputs.items():
            target = ROOT / path
            if not target.exists() or target.read_text(encoding='utf-8') != content:
                if check:
                    bad.append(path)
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(content, encoding='utf-8', newline='') if sys.version_info >= (3, 10) else target.write_bytes(content.encode())
        if bad:
            raise ValueError('Generated files differ: ' + ', '.join(bad))
        print('Pinned contract: %d operations; %d types; generated files %s.' % (len(self.operations), len(self.schemas), 'verified' if check else 'written'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        generator = Generator()
        generator.generate()
        generator.write(args.check)
    except (ValueError, KeyError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
